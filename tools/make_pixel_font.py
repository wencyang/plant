chars=list(range(32,127))+[ord(x) for x in '·×±→←↑↓↳…—–½°']
w,h=128,80
pixels=bytearray(w*h*4)
entries=[]
for i,code in enumerate(chars):
    c=chr(code); x=(i%16)*8; y=(i//16)*10
    pattern=ROWS.get(c,ROWS.get(c.upper(),ROWS['?'])) if c!=' ' else '00000 '*7
    for yy,row in enumerate(pattern.split()):
        for xx,bit in enumerate(row):
            if bit=='1':
                p=((y+yy)*w+x+xx)*4
                pixels[p:p+4]=bytes([255]*4)
    entries.append(f'char id={code} x={x} y={y} width={0 if c==" " else 5} height=7 xoffset=0 yoffset=1 xadvance={4 if c==" " else 6} page=0 chnl=15')
def chunk(name,data): return struct.pack('!I',len(data))+name+data+struct.pack('!I',zlib.crc32(name+data)&0xffffffff)
raw=b''.join(b'\0'+pixels[y*w*4:(y+1)*w*4] for y in range(h))
out=Path(__file__).resolve().parent.parent/'assets'
out.mkdir(exist_ok=True)
(out/'pixel_font.png').write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',w,h,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b''))
(out/'pixel_font.fnt').write_text('\n'.join(['info face="Conservatory Pixel" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1','common lineHeight=10 base=8 scaleW=128 scaleH=80 pages=1 packed=0','page id=0 file="pixel_font.png"',f'chars count={len(entries)}',*entries,'kernings count=0'])+'\n')
